package org.lblocker

import android.content.Context
import android.util.Log
import org.json.JSONArray

/** One verse: Arabic text, English translation and the name of its audio file in res/raw. */
data class Verse(val ref: String, val arabic: String, val translation: String, val raw: String)

object Content {
    const val PLEDGE = "I'm not going to look at any haram things, Allah sees me."

    val reminders = listOf(
        "Small, repeated mistakes compound. Every day you repeat this, it costs you more in the long run.",
        "This urge rises, peaks and passes. Ride it out for ten minutes and it is gone.",
        "What you do in private is who you are becoming in public.",
        "The pleasure lasts minutes. The habit, the guilt and the distance from Allah last far longer.",
        "You are not weak. This exact moment is where you decide who you are.",
        "Allah sees you, even when no one else does. Let that be a comfort, not a fear.",
        "Every time you say no, the next no gets easier. Every time you say yes, the next yes gets easier.",
        "Imagine the person you will be in a year if you keep choosing this. Is that who you want to be?"
    )

    @Volatile
    private var cached: List<Verse>? = null

    /** Loaded from assets/verses.json (generated by tools/fetch_content.py). */
    fun verses(ctx: Context): List<Verse> {
        cached?.let { return it }
        val list = try {
            val text = ctx.assets.open("verses.json").bufferedReader().use { it.readText() }
            val arr = JSONArray(text)
            (0 until arr.length()).map {
                val o = arr.getJSONObject(it)
                Verse(o.getString("ref"), o.getString("arabic"), o.getString("translation"), o.getString("raw"))
            }
        } catch (e: Exception) {
            Log.w("Content", "No verses.json yet - run tools/fetch_content.py", e)
            emptyList()
        }
        cached = list
        return list
    }

    /** Compare pledges ignoring case, spaces and punctuation. */
    fun pledgeMatches(typed: String): Boolean = norm(typed) == norm(PLEDGE)

    private fun norm(s: String) = s.lowercase().filter { it.isLetterOrDigit() }
}
